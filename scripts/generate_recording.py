"""Create two explicitly synthetic screen recordings for media-pipeline inspection."""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
from PIL import Image, ImageDraw, ImageFont
import imageio_ffmpeg
ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "var/generated-demo"
DEST.mkdir(parents=True, exist_ok=True)
FONT_PATH = Path("C:/Windows/Fonts/arial.ttf") if os.name == "nt" else Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
font = ImageFont.truetype(str(FONT_PATH), 28) if FONT_PATH.exists() else ImageFont.load_default(size=28)
title = ImageFont.truetype(str(FONT_PATH), 42) if FONT_PATH.exists() else font
wav = DEST / "narration.wav"
if os.name == "nt":
    # Fixed generated narration, not a transcript or real streamer observation.
    ps = "$ErrorActionPreference = 'Stop'; Add-Type -AssemblyName System.Speech; $voice = New-Object System.Speech.Synthesis.SpeechSynthesizer; $voice.Rate = -1; $voice.SetOutputToWaveFile('" + str(wav).replace("'", "''") + "'); $voice.Speak('The story in this game is excellent. The dialogue in this game is repetitive.'); $voice.Dispose()"
    subprocess.run(["powershell.exe", "-NoProfile", "-NonInteractive", "-Command", ps], check=True)
else:
    import shutil
    if not shutil.which("espeak"):
        raise SystemExit("Install espeak for generated narration, or use your own recording manifest. Windows uses built-in SAPI.")
    subprocess.run(["espeak", "-w", str(wav), "The story in this game is excellent. The dialogue in this game is repetitive."], check=True)
assets = []
for number in (1, 2):
    video = DEST / f"generated-screen-{number}.mp4"
    ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()
    command = [ffmpeg, "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", "1280x720", "-r", "5", "-i", "pipe:0", "-i", str(wav), "-c:v", "libx264", "-preset", "fast", "-pix_fmt", "yuv420p", "-c:a", "aac", "-af", "apad", "-t", "12", "-movflags", "+faststart", str(video)]
    process = subprocess.Popen(command, stdin=subprocess.PIPE)
    try:
        for frame in range(60):
            image = Image.new("RGB", (1280, 720), "#08131d")
            draw = ImageDraw.Draw(image)
            draw.rectangle((640, 0, 1279, 719), fill="white")
            draw.text((34, 42), "GENERATED TEST", font=title, fill="#74e6bd")
            draw.text((34, 112), "No Twitch or GTA footage", font=font, fill="white")
            draw.text((34, 166), f"Source {number} / {frame / 5:.1f} seconds", font=font, fill="white")
            draw.text((34, 230), "Synthetic voice and chat", font=font, fill="#a5b7c4")
            draw.rectangle((60 + frame * 4, 420, 180 + frame * 4, 500), fill="#2b7c76")
            draw.text((670, 34), f"TEST CHAT / SOURCE {number}", font=font, fill="black")
            if frame < 20:
                lines = ["viewer: The story is excellent", "viewer: The game is great"]
            elif frame < 40:
                lines = ["viewer: The story is excellent", "viewer: The dialogue is repetitive"]
            else:
                lines = ["viewer: The dialogue is repetitive", "viewer: The controls are terrible"]
            for index, line in enumerate(lines):
                draw.text((670, 145 + index * 70), line, font=font, fill="black")
            process.stdin.write(image.tobytes())
    finally:
        process.stdin.close()
    if process.wait() != 0:
        raise SystemExit("FFmpeg could not encode generated test media")
    assets.append(dict(asset_id=f"generated-{number}", stream_id=f"generated-stream-{number}", label=f"Generated test recording {number}", local_path=video.relative_to(ROOT).as_posix(), asset_sha256=hashlib.sha256(video.read_bytes()).hexdigest(), availability_reason=None, evidence_mode="synthetic_replay", media_start_seconds=0 if number == 1 else 2, timeline_start_seconds=0 if number == 1 else 1, chat_region=dict(x=.5, y=0, width=.5, height=1), sample_interval_seconds=2, language="eng", permission_note="Generated by this repository; synthetic test graphics/chat/SAPI voice, not actual GTA V or Twitch footage.", scene_id="generated-narrative-scene", audio_transcription="faster_whisper", speech_model_path="var/models/faster-whisper-tiny.en", speaker_role="streamer"))
manifest = dict(schema_version="2", manifest_version="generated-media-v1", recordings=assets, ocr_version="rapidocr-onnxruntime-v1", preprocessing_version="local-media-v1", semantic_version="conservative-lexical-v1")
path = DEST / "manifest.json"
path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
print("Generated synthetic test media and manifest:", path)
